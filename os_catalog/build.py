#!/usr/bin/env python3
"""Build OS Master Catalog: SQLite DB + browsable HTML dashboard."""
import sqlite3, json, html, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'data'))
from os_data import DATA

BASE = os.path.dirname(os.path.abspath(__file__))
DB = os.path.join(BASE, 'os_catalog.db')
OUT_HTML = os.path.join(BASE, 'OS_MASTER_CATALOG.html')

FIELDS = ['name','developer','year','family','purpose','arch','license','kernel_or_parent','status']

def build_db():
    if os.path.exists(DB): os.remove(DB)
    c = sqlite3.connect(DB); c.row_factory = sqlite3.Row
    c.execute('''CREATE TABLE os_entries(
        id INTEGER PRIMARY KEY, category TEXT, name TEXT, developer TEXT,
        year TEXT, family TEXT, purpose TEXT, arch TEXT, license TEXT,
        kernel_or_parent TEXT, status TEXT, source TEXT)''')
    n = 0
    for cat, rows in DATA.items():
        for r in rows:
            if r[0] == 'NixOS (see Desktop)': continue
            c.execute('INSERT INTO os_entries(category,name,developer,year,family,purpose,arch,license,kernel_or_parent,status,source) VALUES(?,?,?,?,?,?,?,?,?,?,?)',
                      (cat,)+tuple(r)+('Wikipedia + vendor docs',))
            n += 1
    c.commit()
    # indexes
    c.execute('CREATE INDEX idx_cat ON os_entries(category)')
    c.execute('CREATE INDEX idx_name ON os_entries(name)')
    c.commit(); c.close()
    return n

def esc(s): return html.escape(str(s))

def build_html(n):
    c = sqlite3.connect(DB); c.row_factory = sqlite3.Row
    rows = c.execute('SELECT * FROM os_entries ORDER BY category, name').fetchall()
    c.close()

    # stats
    cats = {}
    for r in rows: cats[r['category']] = cats.get(r['category'],0)+1
    status_count = {}
    for r in rows:
        key = 'Active' if 'Active' in r['status'] else ('Discontinued' if 'Discontinued' in r['status'] else 'Historical/Niche')
        status_count[key] = status_count.get(key,0)+1

    cats_sorted = sorted(cats.items())
    nav = ''.join(f'<a href="#cat{i+1}">{esc(k)} <span class="cnt">{v}</span></a>' for i,(k,v) in enumerate(cats_sorted))

    body = ''
    cur = None; first = True; ci = 0
    for i, r in enumerate(rows):
        if r['category'] != cur:
            if not first: body += '</div>'
            first = False
            cur = r['category']; ci += 1
            body += f'<h2 id="cat{ci}">{esc(cur)}</h2><div class="grid">'
        body += f'''<div class="card"><div class="osname">{esc(r['name'])}</div>
<div class="meta"><b>Dev:</b> {esc(r['developer'])} · <b>Year:</b> {esc(r['year'])} · <b>Status:</b> {esc(r['status'])}</div>
<div class="meta"><b>Family:</b> {esc(r['family'])} · <b>Arch:</b> {esc(r['arch'])}</div>
<div class="meta"><b>Purpose:</b> {esc(r['purpose'])}</div>
<div class="meta"><b>License:</b> {esc(r['license'])} · <b>Kernel/Parent:</b> {esc(r['kernel_or_parent'])}</div></div>'''
    body += '</div>'

    stats_html = ''.join(f'<div class="stat"><div class="num">{v}</div><div class="lbl">{k}</div></div>' for k,v in sorted(status_count.items()))

    doc = f'''<!DOCTYPE html><html><head><meta charset="utf-8"><title>OS Master Catalog</title>
<style>
body{{font-family:system-ui,Segoe UI,sans-serif;background:#0d1117;color:#e6edf3;margin:0;padding:24px}}
h1{{color:#58a6ff}} h2{{color:#79c0ff;border-bottom:1px solid #30363d;padding-top:24px}}
.stats{{display:flex;gap:16px;margin:16px 0}}
.stat{{background:#161b22;border:1px solid #30363d;border-radius:8px;padding:12px 20px;text-align:center}}
.num{{font-size:28px;font-weight:700;color:#3fb950}} .lbl{{color:#8b949e;font-size:12px}}
nav{{position:sticky;top:0;background:#0d1117;padding:10px 0;border-bottom:1px solid #30363d;z-index:9}}
nav a{{color:#58a6ff;margin-right:14px;text-decoration:none;font-size:13px}}
nav a:hover{{text-decoration:underline}} .cnt{{color:#8b949e}}
.grid{{display:grid;grid-template-columns:repeat(auto-fill,minmax(340px,1fr));gap:12px;margin-bottom:20px}}
.card{{background:#161b22;border:1px solid #30363d;border-radius:8px;padding:12px}}
.osname{{font-weight:700;color:#f0f6fc;font-size:15px}}
.meta{{font-size:12px;color:#8b949e;margin-top:3px}}
.meta b{{color:#c9d1d9}}
.foot{{color:#8b949e;font-size:12px;margin-top:30px}}
</style></head><body>
<h1>🖥️ OS MASTER CATALOG</h1>
<div class="stats"><div class="stat"><div class="num">{n}</div><div class="lbl">Operating Systems</div></div>{stats_html}
<div class="stat"><div class="num">{len(cats)}</div><div class="lbl">Categories</div></div></div>
<nav>{nav}</nav>
{body}
<div class="foot">Built: {n} verified OS entries across {len(cats)} categories · SQLite: os_catalog.db · Sources: Wikipedia + vendor docs · Generated by os_catalog/build.py</div>
</body></html>'''
    open(OUT_HTML,'w',encoding='utf-8').write(doc)
    return OUT_HTML

if __name__ == '__main__':
    n = build_db()
    out = build_html(n)
    print(f'OK: {n} OS entries → {out}')
